const NOTE_LENGTH: usize = 200_000;
const NAME_LENGTH: usize = 1364;

fn write_package(root: &Path, library: &str, tests: Option<&str>) {
    fs::create_dir_all(root.join("src")).expect("source directory is creatable");
    fs::create_dir_all(root.join("tests")).expect("tests directory is creatable");
    fs::write(root.join("Cargo.toml"), "[package]\nname = \"oversized\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n").expect("manifest is writable");
    fs::write(root.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"oversized\"\nversion = \"0.1.0\"\n").expect("lockfile is writable");
    fs::write(root.join("src/lib.rs"), library).expect("library is writable");
    if let Some(body) = tests {
        fs::write(root.join("tests/long_names.rs"), body).expect("test file is writable");
    }
}

fn cargo_val(scratch: &Path) -> Command {
    let mut command = binary::command();
    command
        .arg("--manifest-path")
        .arg(scratch.join("Cargo.toml"))
        .args(["--no-fail-fast", "--tests"])
        .env("CARGO_VAL_OUTPUT", "plain")
        .env("NO_COLOR", "1")
        .env("CARGO_HOME", scratch.join("cargo-home"))
        .env("CARGO_TARGET_DIR", scratch.join("target"));
    for key in ["CARGO_VAL_BIN_GATE", "CARGO_VAL_TARGET_DIR", "CARGO_VAL_JOBS", "RUST_TEST_THREADS", "CARGO_VAL_LOG"] {
        command.env_remove(key);
    }
    command
}

fn count(stdout: &str, field: &str) -> usize {
    let total = stdout
        .lines()
        .find(|line| line.starts_with("SUMMARY  "))
        .unwrap_or_else(|| panic!("a summary line is printed:\n{stdout}"));
    total
        .split_whitespace()
        .find_map(|part| part.strip_prefix(field))
        .and_then(|number| number.parse().ok())
        .unwrap_or_else(|| panic!("the total line carries {field}: {total}"))
}

#[proxima::test(timeout = "310s")]
async fn a_200_kilobyte_cargo_message_does_not_end_the_run() {
    let scratch = Scratch::new("oversized-message");
    let note = "a".repeat(NOTE_LENGTH);
    let library = format!("#[deprecated(note = \"{note}\")]\npub fn old() {{}}\n\n#[test]\nfn uses_the_deprecated_function() {{\n    old();\n}}\n");
    write_package(&scratch, &library, None);

    let output = fixture_output(&mut cargo_val(&scratch)).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert_eq!(output.status.code(), Some(0), "{}{}", &stdout[..stdout.len().min(2000)], &stderr[..stderr.len().min(2000)]);
    assert_eq!(count(&stdout, "passed="), 1, "{stdout}");
}

#[proxima::test(timeout = "310s")]
async fn an_ignored_test_named_1364_bytes_is_listed_and_counted() {
    let scratch = Scratch::new("long-ignored-name");
    let stem = "an_ignored_test_whose_name_is_longer_than_the_ignored_listing_line_buffer_";
    let name: String = stem.repeat(NAME_LENGTH / stem.len() + 1).chars().take(NAME_LENGTH).collect();
    let body = format!("#[test]\n#[ignore]\nfn {name}() {{\n    assert_eq!(2 + 2, 4);\n}}\n\n#[test]\nfn the_plain_neighbour_runs() {{\n    assert_eq!(1 + 1, 2);\n}}\n");
    write_package(&scratch, "", Some(&body));

    let output = fixture_output(&mut cargo_val(&scratch)).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert_eq!(output.status.code(), Some(0), "{}{}", &stdout[..stdout.len().min(2000)], &stderr[..stderr.len().min(2000)]);
    assert_eq!(count(&stdout, "passed="), 1, "{stdout}");
    assert_eq!(count(&stdout, "ignored="), 1, "{stdout}");
}
