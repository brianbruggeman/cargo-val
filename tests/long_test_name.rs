const NAME_LENGTH: usize = 1364;

fn long_name() -> String {
    let stem = "a_test_function_whose_name_is_longer_than_any_fixed_name_buffer_once_held_";
    let mut name = String::from(stem);
    while name.len() < NAME_LENGTH {
        name.push_str(stem);
    }
    name.truncate(NAME_LENGTH);
    name
}

fn write_package(root: &Path, name: &str) {
    fs::write(root.join("Cargo.toml"), "[package]\nname = \"named_at_length\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n").expect("manifest is writable");
    fs::write(root.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"named_at_length\"\nversion = \"0.1.0\"\n").expect("lockfile is writable");
    fs::write(root.join("src/lib.rs"), "").expect("library is writable");
    let body = format!("#[test]\nfn {name}() {{\n    assert_eq!(2 + 2, 4);\n}}\n\n#[test]\nfn the_short_neighbour_still_runs() {{\n    assert_eq!(1 + 1, 2);\n}}\n");
    fs::write(root.join("tests/named.rs"), body).expect("test file is writable");
}

fn cargo_val(scratch: &Path) -> Command {
    let mut command = binary::command();
    command
        .arg("--manifest-path")
        .arg(scratch.join("Cargo.toml"))
        .args(["--no-fail-fast", "--tests"])
        .env("CARGO_VAL_OUTPUT", "plain")
        .env("NO_COLOR", "1")
        .envs(isolation::environment("long-test-name"));
    for key in ["CARGO_VAL_BIN_GATE", "CARGO_VAL_TARGET_DIR", "CARGO_VAL_JOBS", "RUST_TEST_THREADS", "CARGO_VAL_LOG"] {
        command.env_remove(key);
    }
    command
}

fn passed(stdout: &str) -> usize {
    let total = stdout
        .lines()
        .find(|line| line.starts_with("SUMMARY  "))
        .unwrap_or_else(|| panic!("a summary line is printed:\n{stdout}"));
    total
        .split_whitespace()
        .find_map(|part| part.strip_prefix("passed="))
        .and_then(|count| count.parse().ok())
        .unwrap_or_else(|| panic!("the total line carries a passed count: {total}"))
}

#[proxima::test(timeout = "310s")]
async fn a_1364_byte_test_name_runs_and_is_counted_in_the_summary() {
    let scratch = Scratch::new("long-test-name");
    fs::create_dir_all(scratch.join("src")).expect("source directory is creatable");
    fs::create_dir_all(scratch.join("tests")).expect("tests directory is creatable");
    let name = long_name();
    assert_eq!(name.len(), NAME_LENGTH);
    write_package(&scratch, &name);

    let output = fixture_output(&mut cargo_val(&scratch)).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert_eq!(output.status.code(), Some(0), "{stdout}{stderr}");
    assert_eq!(passed(&stdout), 2, "{stdout}{stderr}");
    assert!(stdout.contains(&name), "the whole name is reported:\n{stdout}");
}
