const PATH_FLOOR: usize = 330;
const PACKAGE: &str = "identifiers_under_a_workspace_path_that_no_fixed_buffer_was_sized_for";
const BIN_NAME: &str = "serve_requests_from_a_binary_whose_name_is_far_longer_than_any_buffer_once_held_one";
const TEST_NAME: &str = "a_test_function_named_at_great_length_to_prove_that_no_name_buffer_truncates_or_refuses_it";

fn long_root(scratch: &Path) -> PathBuf {
    let mut root = scratch.to_path_buf();
    let mut level = 0;
    while root.as_os_str().len() <= PATH_FLOOR {
        root.push(format!("segment_{level:02}_{}", "d".repeat(28)));
        level += 1;
    }
    root
}

fn write_package(root: &Path) {
    fs::create_dir_all(root.join("src")).expect("source directory is creatable");
    fs::create_dir_all(root.join("tests")).expect("tests directory is creatable");
    fs::write(
        root.join("Cargo.toml"),
        format!("[package]\nname = \"{PACKAGE}\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n[[bin]]\nname = \"{BIN_NAME}\"\npath = \"src/main.rs\"\n"),
    )
    .expect("manifest is writable");
    fs::write(root.join("Cargo.lock"), format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"{PACKAGE}\"\nversion = \"0.1.0\"\n"))
        .expect("lockfile is writable");
    fs::write(root.join("src/main.rs"), "fn main() {\n    println!(\"serving\");\n}\n").expect("main is writable");
    let body = format!(
        "#[test]\nfn {TEST_NAME}() {{\n    let output = std::process::Command::new(env!(\"CARGO_BIN_EXE_{BIN_NAME}\")).output().expect(\"the bin starts\");\n    assert_eq!(output.stdout, b\"serving\\n\");\n}}\n\n#[test]\nfn second_{TEST_NAME}() {{\n    assert_eq!(1 + 1, 2);\n}}\n"
    );
    fs::write(root.join("tests/exercise_the_long_names.rs"), body).expect("test file is writable");
}

fn cargo_val(scratch: &Path, package: &Path, target: &Path) -> Command {
    let mut command = binary::command();
    command
        .arg("--manifest-path")
        .arg(package.join("Cargo.toml"))
        .args(["--no-fail-fast", "--tests", "--target-dir", "isolated"])
        .env("CARGO_VAL_OUTPUT", "plain")
        .env("NO_COLOR", "1")
        .env("CARGO_HOME", scratch.join("cargo-home"))
        .env("CARGO_TARGET_DIR", target);
    for key in ["CARGO_VAL_BIN_GATE", "CARGO_VAL_TARGET_DIR", "CARGO_VAL_JOBS", "RUST_TEST_THREADS", "CARGO_VAL_LOG"] {
        command.env_remove(key);
    }
    command
}

fn passed(stdout: &str) -> usize {
    let total = stdout
        .lines()
        .find(|line| line.starts_with("SUMMARY  "))
        .unwrap_or_else(|| panic!("a summary line is printed:\n{stdout}"));
    total
        .split_whitespace()
        .find_map(|part| part.strip_prefix("passed="))
        .and_then(|count| count.parse().ok())
        .unwrap_or_else(|| panic!("the total line carries a passed count: {total}"))
}

#[proxima::test(timeout = "310s")]
async fn a_331_character_workspace_path_with_long_binary_and_test_names_completes_with_a_summary() {
    let scratch = Scratch::new("long-identifiers");
    let root = long_root(&scratch);
    write_package(&root);
    assert!(root.as_os_str().len() > PATH_FLOOR, "the package path is {} characters", root.as_os_str().len());

    let output = fixture_output(&mut cargo_val(&scratch, &root, &root.join("target"))).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert_eq!(output.status.code(), Some(0), "{stdout}{stderr}");
    assert_eq!(passed(&stdout), 2, "{stdout}{stderr}");
    assert!(stdout.contains(TEST_NAME), "the long test name is reported whole:\n{stdout}");
}
