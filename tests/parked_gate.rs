const PACKAGES: [&str; 2] = ["gate_alpha", "gate_beta"];
const TESTS_PER_PACKAGE: usize = 35;
const PARK_CAPACITY_BEFORE_THE_FIX: usize = 64;

fn scratch(label: &str) -> PathBuf {
    let directory = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("{label}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&directory);
    fs::create_dir_all(&directory).expect("scratch directory is creatable");
    directory
}

// each package has the bin its tests run and a second bin behind a feature nobody enables: metadata counts two bins, cargo builds one, so the second never arrives and every integration test of the package parks until cargo reports build-finished
fn write_package(workspace: &Path, name: &str) {
    let root = workspace.join(name);
    fs::create_dir_all(root.join("src")).expect("package source directory is creatable");
    fs::create_dir_all(root.join("tests")).expect("package tests directory is creatable");
    fs::write(
        root.join("Cargo.toml"),
        format!(
            "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n[features]\nextra = []\n\n[[bin]]\nname = \"serve\"\npath = \"src/main.rs\"\n\n[[bin]]\nname = \"extra\"\npath = \"src/extra.rs\"\nrequired-features = [\"extra\"]\n"
        ),
    )
    .expect("package manifest is writable");
    fs::write(root.join("src/main.rs"), "fn main() {\n    println!(\"serving\");\n}\n").expect("main is writable");
    fs::write(root.join("src/extra.rs"), "fn main() {\n    println!(\"extra\");\n}\n").expect("extra is writable");
    for number in 0..TESTS_PER_PACKAGE {
        let body = format!(
            "#[test]\nfn serve_exits_cleanly_{number:02}() {{\n    let output = std::process::Command::new(env!(\"CARGO_BIN_EXE_serve\")).output().expect(\"the serve bin starts\");\n    assert!(output.status.success());\n    assert_eq!(output.stdout, b\"serving\\n\");\n}}\n"
        );
        fs::write(root.join(format!("tests/serve_{number:02}.rs")), body).expect("test file is writable");
    }
}

fn write_workspace(scratch: &Path) -> PathBuf {
    let workspace = scratch.join("workspace");
    fs::create_dir_all(&workspace).expect("workspace directory is creatable");
    let members = PACKAGES.map(|name| format!("\"{name}\"")).join(", ");
    fs::write(workspace.join("Cargo.toml"), format!("[workspace]\nmembers = [{members}]\nresolver = \"3\"\n")).expect("workspace manifest is writable");
    let mut locked = String::new();
    for name in PACKAGES {
        write!(locked, "\n[[package]]\nname = \"{name}\"\nversion = \"0.1.0\"\n").expect("a string accepts writes");
    }
    fs::write(workspace.join("Cargo.lock"), format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n{locked}")).expect("lockfile is writable");
    for name in PACKAGES {
        write_package(&workspace, name);
    }
    workspace
}

fn cargo_val(scratch: &Path, workspace: &Path) -> Command {
    let mut command = binary::command();
    command
        .arg("--manifest-path")
        .arg(workspace.join("Cargo.toml"))
        .args(["--no-fail-fast", "--tests"])
        .env("CARGO_VAL_OUTPUT", "plain")
        .env("CARGO_VAL_LOG", "debug")
        .env("NO_COLOR", "1")
        .env("CARGO_HOME", scratch.join("cargo-home"))
        .env("CARGO_TARGET_DIR", scratch.join("target"));
    for key in ["CARGO_VAL_BIN_GATE", "CARGO_VAL_TARGET_DIR", "CARGO_VAL_JOBS", "RUST_TEST_THREADS"] {
        command.env_remove(key);
    }
    command
}

fn passed(stdout: &str) -> usize {
    let total = stdout
        .lines()
        .find(|line| line.starts_with("SUMMARY  "))
        .unwrap_or_else(|| panic!("a summary line is printed:\n{stdout}"));
    total
        .split_whitespace()
        .find_map(|part| part.strip_prefix("passed="))
        .and_then(|count| count.parse().ok())
        .unwrap_or_else(|| panic!("the total line carries a passed count: {total}"))
}

#[proxima::test(timeout = "310s")]
async fn more_test_binaries_than_the_old_park_capacity_wait_for_a_bin_and_every_test_runs() {
    let scratch = scratch("parked-gate");
    let workspace = write_workspace(&scratch);

    let output = fixture_output(&mut cargo_val(&scratch, &workspace)).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    let parks = stderr.lines().filter(|line| line.contains("gate park kind=test") && line.contains("gate=metadata")).count();
    assert!(parks > PARK_CAPACITY_BEFORE_THE_FIX, "the gate parked {parks} test binaries, which must exceed the old capacity of {PARK_CAPACITY_BEFORE_THE_FIX}:\n{stderr}");
    assert_eq!(output.status.code(), Some(0), "{stdout}{stderr}");
    assert_eq!(passed(&stdout), PACKAGES.len() * TESTS_PER_PACKAGE, "{stdout}");
}
