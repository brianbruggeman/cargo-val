const PACKAGES: [&str; 2] = ["gate_alpha", "gate_beta"];
const TESTS_PER_PACKAGE: usize = 35;
const PARK_CAPACITY_BEFORE_THE_FIX: usize = 64;
#[cfg(unix)]
const LONG_PATH_FLOOR: usize = 300;

// each package has the bin its tests run and a second bin behind a feature nobody enables: metadata counts two bins, cargo builds one, so the second never arrives and every integration test of the package parks until cargo reports build-finished
fn write_package(workspace: &Path, name: &str, tests: usize) {
    let root = workspace.join(name);
    fs::create_dir_all(root.join("src")).expect("package source directory is creatable");
    fs::create_dir_all(root.join("tests")).expect("package tests directory is creatable");
    fs::write(
        root.join("Cargo.toml"),
        format!(
            "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n[features]\nextra = []\n\n[[bin]]\nname = \"{name}_serve\"\npath = \"src/main.rs\"\n\n[[bin]]\nname = \"{name}_extra\"\npath = \"src/extra.rs\"\nrequired-features = [\"extra\"]\n"
        ),
    )
    .expect("package manifest is writable");
    fs::write(root.join("src/main.rs"), "fn main() {\n    println!(\"serving\");\n}\n").expect("main is writable");
    fs::write(root.join("src/extra.rs"), "fn main() {\n    println!(\"extra\");\n}\n").expect("extra is writable");
    for number in 0..tests {
        let body = format!(
            "#[test]\nfn serve_exits_cleanly_{number:02}() {{\n    let output = std::process::Command::new(env!(\"CARGO_BIN_EXE_{name}_serve\")).stdout(std::process::Stdio::piped()).spawn().expect(\"the serve bin starts\").wait_with_output().expect(\"the serve bin exits\");\n    assert!(output.status.success());\n    assert_eq!(output.stdout, b\"serving\\n\");\n}}\n"
        );
        fs::write(root.join(format!("tests/serve_{number:02}.rs")), body).expect("test file is writable");
    }
}

fn write_workspace(root: &Path, tests: usize) -> PathBuf {
    let workspace = root.join("workspace");
    fs::create_dir_all(&workspace).expect("workspace directory is creatable");
    let members = PACKAGES.map(|name| format!("\"{name}\"")).join(", ");
    fs::write(workspace.join("Cargo.toml"), format!("[workspace]\nmembers = [{members}]\nresolver = \"3\"\n")).expect("workspace manifest is writable");
    let mut locked = String::new();
    for name in PACKAGES {
        write!(locked, "\n[[package]]\nname = \"{name}\"\nversion = \"0.1.0\"\n").expect("a string accepts writes");
    }
    fs::write(workspace.join("Cargo.lock"), format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n{locked}")).expect("lockfile is writable");
    for name in PACKAGES {
        write_package(&workspace, name, tests);
    }
    workspace
}

fn cargo_val(workspace: &Path) -> Command {
    let mut command = binary::command();
    command
        .arg("--manifest-path")
        .arg(workspace.join("Cargo.toml"))
        .args(["--no-fail-fast", "--tests"])
        .env("CARGO_VAL_OUTPUT", "plain")
        .env("CARGO_VAL_LOG", "debug")
        .env("NO_COLOR", "1")
        .envs(isolation::environment("parked-gate"));
    for key in ["CARGO_VAL_BIN_GATE", "CARGO_VAL_TARGET_DIR", "CARGO_VAL_JOBS", "RUST_TEST_THREADS"] {
        command.env_remove(key);
    }
    command
}

fn passed(stdout: &str) -> usize {
    let total = stdout
        .lines()
        .find(|line| line.starts_with("SUMMARY  "))
        .unwrap_or_else(|| panic!("a summary line is printed:\n{stdout}"));
    total
        .split_whitespace()
        .find_map(|part| part.strip_prefix("passed="))
        .and_then(|count| count.parse().ok())
        .unwrap_or_else(|| panic!("the total line carries a passed count: {total}"))
}

#[proxima::test(timeout = "310s")]
async fn more_test_binaries_than_the_old_park_capacity_wait_for_a_bin_and_every_test_runs() {
    let scratch = Scratch::new("parked-gate");
    let workspace = write_workspace(&scratch, TESTS_PER_PACKAGE);
    let mut command = cargo_val(&workspace);
    command.arg("--no-default-features");

    let output = fixture_output(&mut command).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert!(stderr.contains("gate bin-features unknown-packages=2 reason=feature-flags wait=build-finished"), "the gate said why it waits for build-finished:\n{stderr}");
    let parks = stderr.lines().filter(|line| line.contains("gate park why=bin-gate kind=test") && line.contains("gate=metadata")).count();
    assert!(parks > PARK_CAPACITY_BEFORE_THE_FIX, "the gate parked {parks} test binaries, which must exceed the old capacity of {PARK_CAPACITY_BEFORE_THE_FIX}:\n{stderr}");
    assert_eq!(output.status.code(), Some(0), "{stdout}{stderr}");
    assert_eq!(passed(&stdout), PACKAGES.len() * TESTS_PER_PACKAGE, "{stdout}");
}

// a directory chain of 40-character names until the path passes the floor, so every id and directory cargo-val holds is longer than any fixed field once held
#[cfg(unix)]
fn long_root(scratch: &Path) -> PathBuf {
    let mut root = scratch.to_path_buf();
    let mut level = 0;
    while root.as_os_str().len() <= LONG_PATH_FLOOR {
        root.push(format!("segment_{level:02}_{}", "d".repeat(28)));
        level += 1;
    }
    fs::create_dir_all(&root).expect("long root is creatable");
    root
}

#[cfg(unix)]
#[proxima::test(timeout = "310s")]
async fn a_workspace_path_over_300_characters_keeps_its_metadata_so_the_run_isolates_and_gates_on_metadata() {
    let scratch = Scratch::new("long-path");
    let root = long_root(&scratch);
    let workspace = write_workspace(&root, 2);
    let mut command = cargo_val(&workspace);
    command.args(["--target-dir", "isolated"]);

    let output = fixture_output(&mut command).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert!(workspace.as_os_str().len() > LONG_PATH_FLOOR, "the workspace path is {} characters", workspace.as_os_str().len());
    assert!(!stderr.contains("no usable target directory"), "isolation fell back to the shared directory:\n{stderr}");
    let built = stderr.lines().find(|line| line.contains("gate bin-built")).unwrap_or_else(|| panic!("a bin-built line is printed:\n{stderr}"));
    assert!(built.contains("/cargo-val/"), "the bin was built under the isolated subtree: {built}");
    assert!(stderr.lines().any(|line| line.contains("gate launch kind=test") && line.contains("gate=metadata")), "the gate decided from metadata:\n{stderr}");
    assert_eq!(output.status.code(), Some(0), "{stdout}{stderr}");
    assert_eq!(passed(&stdout), PACKAGES.len() * 2, "{stdout}");
}

#[proxima::test(timeout = "310s")]
async fn a_required_features_bin_that_is_not_enabled_does_not_hold_tests_past_the_other_bins_artifact() {
    let scratch = Scratch::new("required-features");
    let workspace = write_workspace(&scratch, TESTS_PER_PACKAGE);

    let output = fixture_output(&mut cargo_val(&workspace)).await;
    let stderr = String::from_utf8_lossy(&output.stderr);

    let lines: Vec<&str> = stderr.lines().collect();
    for package in PACKAGES {
        let owned = format!("/{package}#");
        let built: Vec<usize> = lines.iter().enumerate().filter(|(_, line)| line.contains("gate bin-built") && line.contains(&owned)).map(|(index, _)| index).collect();
        assert_eq!(built.len(), 1, "{package}: its one enabled bin was built:\n{stderr}");
        let held_after = lines[built[0]..].iter().filter(|line| line.contains("gate park why=bin-gate kind=test") && line.contains(&owned)).count();
        assert_eq!(held_after, 0, "{package}: tests that arrived after its bin artifact were parked for the bin that is not enabled:\n{stderr}");
    }
    assert_eq!(output.status.code(), Some(0), "{stderr}");
}
