const PACKAGES: usize = 300;
const SEARCH_DIRECTORIES: usize = 3;
const PAD: &str = "padding_so_each_search_directory_is_a_realistic_build_output_path_length";

fn package_name(number: usize) -> String {
    format!("scripted_{number:03}")
}

fn write_package(workspace: &Path, number: usize) {
    let name = package_name(number);
    let root = workspace.join(&name);
    fs::create_dir_all(root.join("src")).expect("source directory is creatable");
    fs::write(root.join("Cargo.toml"), format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\nbuild = \"build.rs\"\n")).expect("manifest is writable");
    let script = format!(
        "fn main() {{\n    let out = std::env::var(\"OUT_DIR\").expect(\"cargo sets OUT_DIR\");\n    for search in 0..{SEARCH_DIRECTORIES} {{\n        println!(\"cargo:rustc-link-search=native={{out}}/search_{{search}}_{PAD}\");\n    }}\n    println!(\"cargo:rustc-env=SCRIPT_MARK=mark_{name}\");\n    println!(\"cargo:rustc-env=SCRIPT_PAD_ONE={PAD}_one\");\n    println!(\"cargo:rustc-env=SCRIPT_PAD_TWO={PAD}_two\");\n    println!(\"cargo:rerun-if-changed=build.rs\");\n}}\n"
    );
    fs::write(root.join("build.rs"), script).expect("build script is writable");
    let library = format!(
        "#[cfg(test)]\nmod tests {{\n    #[test]\n    fn the_build_script_output_of_{name}_reaches_its_test() {{\n        assert_eq!(std::env::var(\"SCRIPT_MARK\").as_deref(), Ok(\"mark_{name}\"));\n        assert!(std::env::var(\"OUT_DIR\").is_ok());\n    }}\n}}\n"
    );
    fs::write(root.join("src/lib.rs"), library).expect("library is writable");
}

fn write_workspace(root: &Path) -> PathBuf {
    let workspace = root.join("workspace");
    fs::create_dir_all(&workspace).expect("workspace directory is creatable");
    let members = (0..PACKAGES).map(|number| format!("\"{}\"", package_name(number))).collect::<Vec<_>>().join(", ");
    fs::write(workspace.join("Cargo.toml"), format!("[workspace]\nmembers = [{members}]\nresolver = \"3\"\n")).expect("workspace manifest is writable");
    let mut locked = String::new();
    for number in 0..PACKAGES {
        write!(locked, "\n[[package]]\nname = \"{}\"\nversion = \"0.1.0\"\n", package_name(number)).expect("a string accepts writes");
    }
    fs::write(workspace.join("Cargo.lock"), format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n{locked}")).expect("lockfile is writable");
    for number in 0..PACKAGES {
        write_package(&workspace, number);
    }
    workspace
}

fn cargo_val(scratch: &Path, workspace: &Path) -> Command {
    let mut command = binary::command();
    command
        .arg("--manifest-path")
        .arg(workspace.join("Cargo.toml"))
        .args(["--no-fail-fast", "--tests", "--target-dir", "isolated"])
        .env("CARGO_VAL_OUTPUT", "plain")
        .env("NO_COLOR", "1")
        .env("CARGO_HOME", scratch.join("cargo-home"))
        .env("CARGO_TARGET_DIR", scratch.join("target"));
    command.env("CARGO_VAL_LOG", "debug");
    for key in ["CARGO_VAL_BIN_GATE", "CARGO_VAL_TARGET_DIR", "CARGO_VAL_JOBS", "RUST_TEST_THREADS"] {
        command.env_remove(key);
    }
    command
}

fn passed(stdout: &str) -> usize {
    let total = stdout
        .lines()
        .find(|line| line.starts_with("SUMMARY  "))
        .unwrap_or_else(|| panic!("a summary line is printed:\n{stdout}"));
    total
        .split_whitespace()
        .find_map(|part| part.strip_prefix("passed="))
        .and_then(|count| count.parse().ok())
        .unwrap_or_else(|| panic!("the total line carries a passed count: {total}"))
}

#[proxima::test(timeout = "900s")]
async fn three_hundred_build_scripts_whose_output_passes_every_old_aggregate_cap_all_reach_their_tests() {
    let scratch = Scratch::new("many-build-scripts");
    let workspace = write_workspace(&scratch);

    let output = fixture_output(&mut cargo_val(&scratch, &workspace)).await;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert_eq!(output.status.code(), Some(0), "{stdout}{stderr}");
    assert_eq!(passed(&stdout), PACKAGES, "{stdout}{stderr}");
    #[cfg(target_os = "linux")]
    assert!(stderr.contains("step=library-path-narrowed"), "the joined path passed one environment string's limit, so each binary got its own closure:\n{}", stderr.lines().take(40).collect::<Vec<_>>().join("\n"));
}
